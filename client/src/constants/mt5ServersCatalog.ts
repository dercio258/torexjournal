export function matchesBrokerServerQuery(
    group: Pick<Mt5BrokerGroup, 'broker' | 'id' | 'category'>,
    server: Pick<Mt5ServerOption, 'name' | 'description'>,
    rawQuery: string,
): boolean {
    const q = rawQuery.trim().toLowerCase();
    if (!q) return true;
    const haystack = `${group.broker} ${group.id} ${group.category} ${server.name} ${server.description || ''}`.toLowerCase();
    if (haystack.includes(q)) return true;
    const tokens = q.split(/[\s_-]+/).filter(Boolean);
    return tokens.length > 0 && tokens.every((tok) => haystack.includes(tok));
}
