export interface Mt5ServerOption {
    name: string;
    env: 'DEMO' | 'REAL';
    description?: string;
}

export interface Mt5BrokerGroup {
    id: string;
    broker: string;
    category: 'Deriv' | 'Prop Firm' | 'Forex / ECN' | 'MetaQuotes';
    domain: string;
    logoUrl: string;
    brandColor: string;
    shortMark: string;
    countryOrRegion?: string;
    popular?: boolean;
    servers: Mt5ServerOption[];
}

function faviconUrl(domain: string): string {
    return `https://www.google.com/s2/favicons?domain=${domain}&sz=128`;
}

function buildNumberedServers(opts: {
    firstName: string;
    numberedPrefix: string;
    start?: number;
    end: number;
    env: 'DEMO' | 'REAL';
    descriptionPrefix: string;
    padWidth?: number;
    includeUnnumberedFirst?: boolean;
}): Mt5ServerOption[] {
    const out: Mt5ServerOption[] = [];
    const start = opts.start ?? 2;
    const fmt = (n: number) => (opts.padWidth ? String(n).padStart(opts.padWidth, '0') : String(n));

    if (opts.includeUnnumberedFirst !== false) {
        out.push({
            name: opts.firstName,
            env: opts.env,
            description: `${opts.descriptionPrefix} 1`,
        });
    }
    for (let n = start; n <= opts.end; n += 1) {
        out.push({
            name: `${opts.numberedPrefix}${fmt(n)}`,
            env: opts.env,
            description: `${opts.descriptionPrefix} ${n}`,
        });
    }
    return out;
}

